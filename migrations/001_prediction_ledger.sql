-- V0.1 prediction ledger schema.
-- Safe to apply repeatedly in Supabase/PostgreSQL.

create table if not exists public.markets (
  ticker text primary key,
  event_ticker text,
  category text not null,
  title text not null,
  subtitle text,
  close_time timestamptz,
  expected_expiration_time timestamptz,
  yes_bid numeric,
  yes_ask numeric,
  no_bid numeric,
  no_ask numeric,
  volume numeric,
  open_interest numeric,
  rules_primary text,
  raw_payload jsonb not null default '{}'::jsonb,
  last_seen_at timestamptz not null default now()
);

create table if not exists public.predictions (
  id bigint generated by default as identity primary key,
  ticker text not null references public.markets(ticker),
  category text not null,
  model_name text not null,
  model_version text not null,
  side text not null,
  market_probability double precision not null,
  raw_model_probability double precision not null,
  calibrated_probability double precision not null,
  edge double precision not null,
  decision text not null check (decision in ('PAPER','PASS')),
  evidence jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  resolved boolean not null default false,
  outcome text check (outcome is null or outcome in ('YES','NO','VOID')),
  resolved_at timestamptz,
  brier_score double precision,
  log_loss double precision
);

create index if not exists predictions_unresolved_paper_idx
  on public.predictions (created_at)
  where resolved=false and decision='PAPER';

create table if not exists public.evidence_snapshots (
  id bigint generated by default as identity primary key,
  prediction_id bigint not null references public.predictions(id) on delete cascade,
  ticker text not null,
  provider text not null,
  source_tier text not null,
  endpoint text,
  retrieved_at timestamptz not null,
  observed_at timestamptz,
  units text,
  stale boolean not null,
  critical boolean not null,
  payload_hash text not null,
  value_json jsonb not null,
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists evidence_prediction_idx
  on public.evidence_snapshots (prediction_id);
